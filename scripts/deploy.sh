#!/bin/bash

# Скрипт для развертывания обновлений на сервере

set -e

echo "🚀 Начинаю развертывание обновлений..."

# Остановка контейнеров
echo "⏹️  Остановка контейнеров..."
docker-compose down

# Обновление кода (если используется git)
if [ -d ".git" ]; then
    echo "📥 Обновление кода из репозитория..."
    git pull
fi

# Пересборка контейнеров
echo "🔨 Пересборка контейнеров..."
docker-compose build --no-cache

# Запуск контейнеров
echo "▶️  Запуск контейнеров..."
docker-compose up -d

# Ожидание готовности базы данных
echo "⏳ Ожидание готовности базы данных..."
sleep 10

# Выполнение миграций
echo "🗄️  Выполнение миграций базы данных..."
docker exec -it hse_bot_app python main.py migrate

# Проверка статуса
echo "✅ Проверка статуса контейнеров..."
docker-compose ps

echo "🎉 Развертывание завершено!"